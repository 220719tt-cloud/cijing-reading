import {createRequire} from 'node:module'
import {readFile,writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
// Reuse Vite's installed bundler; no new package, remote build or deployment.
const require=createRequire(import.meta.url)
const {build}=createRequire(require.resolve('vite/package.json'))('esbuild')
const root=fileURLToPath(new URL('../',import.meta.url))
const output=new URL('../worker/worker.js',import.meta.url)
const result=await build({absWorkingDir:root,entryPoints:['worker/translation.ts'],bundle:true,format:'esm',platform:'browser',target:'es2022',write:false,
 banner:{js:'// Generated by pnpm worker:editor. Paste this ENTIRE file into Cloudflare worker.js.\n// Local build only: this command does not publish or change Cloudflare settings.'}})
const code=result.outputFiles[0].text
if(process.argv.includes('--check')){
 if(await readFile(output,'utf8')!==code)throw new Error('worker/worker.js 已过期，请运行 pnpm worker:editor。')
 console.log('Worker editor bundle matches source; no external imports.')
}else{await writeFile(output,code);console.log('Prepared worker/worker.js (standalone ES module; not deployed).')}
